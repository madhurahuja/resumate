import { launch } from './harness.mjs';
const { browser, page, errors } = await launch({ width: 390, height: 800 });
await page.goto('https://folio.test/');
await page.click('text=Try with sample data');
await page.waitForSelector('button.open-link');
await page.screenshot({ path: 'e2e/out/40-m-dash.png' });
const ov = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
console.log('horizontal overflow dashboard:', ov);
await page.click('article >> nth=0 >> button.open-link');
await page.waitForSelector('.tabpane');
await page.screenshot({ path: 'e2e/out/41-m-edit.png' });
await page.click('.ed-switch button:has-text("Preview")');
await page.waitForTimeout(300);
await page.screenshot({ path: 'e2e/out/42-m-preview.png' });
console.log('overflow editor:', await page.evaluate(() => document.documentElement.scrollWidth > innerWidth));
await page.click('.ed-switch button:has-text("Edit")');
await page.click('button[aria-label="Back to resumes"]');
await page.click('button.nav-btn:has-text("Master")');
