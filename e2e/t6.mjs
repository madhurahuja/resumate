await page.click('.item-head .t >> nth=0');
await page.screenshot({ path: 'e2e/out/43-m-master.png' });
console.log('overflow master:', await page.evaluate(() => document.documentElement.scrollWidth > innerWidth));
console.log(errors.filter((e) => !e.includes('ERR_FAILED')));
